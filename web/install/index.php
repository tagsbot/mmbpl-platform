/**
 * MMBPL web installer. Open https://your-domain/install/ once after uploading the files.
 */
declare(strict_types=1);
define('APP_ROOT', dirname(__DIR__));
session_start();
$configFile = APP_ROOT . '/app/config.php';
$installed = is_file($configFile);

function h($v): string { return htmlspecialchars((string)$v, ENT_QUOTES, 'UTF-8'); }
function base(): string { return rtrim(str_replace('\\', '/', dirname(dirname($_SERVER['SCRIPT_NAME']))), '/'); }

$checks = [
    'PHP 8.1 or newer' => version_compare(PHP_VERSION, '8.1.0', '>='),
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'mbstring extension' => extension_loaded('mbstring'),
    'JSON extension' => extension_loaded('json'),
    'fileinfo extension (upload checks)' => extension_loaded('fileinfo'),
    '"app" folder writable' => is_writable(APP_ROOT . '/app'),
    '"uploads" folder writable' => is_dir(APP_ROOT . '/uploads') && is_writable(APP_ROOT . '/uploads'),
];
$required = ['PHP 8.1 or newer', 'PDO MySQL extension', 'mbstring extension', 'JSON extension', '"app" folder writable', '"uploads" folder writable'];
$canInstall = !$installed && !in_array(false, array_intersect_key($checks, array_flip($required)), true);
$error = '';
$done = false;

if ($_SERVER['REQUEST_METHOD'] === 'POST' && $canInstall) {
    if (!hash_equals($_SESSION['inst_csrf'] ?? '', $_POST['_csrf'] ?? '')) $error = 'Session expired. Reload the page and try again.';
    $db = ['host' => trim($_POST['db_host'] ?? 'localhost'), 'port' => trim($_POST['db_port'] ?? '3306'), 'name' => trim($_POST['db_name'] ?? ''), 'user' => trim($_POST['db_user'] ?? ''), 'pass' => (string)($_POST['db_pass'] ?? '')];
    $adminName = trim($_POST['admin_name'] ?? '');
    $adminEmail = strtolower(trim($_POST['admin_email'] ?? ''));
    $adminPass = (string)($_POST['admin_pass'] ?? '');
    if (!$error && (!$db['name'] || !$db['user'])) $error = 'Enter the database name and user.';
    if (!$error && (!$adminName || !filter_var($adminEmail, FILTER_VALIDATE_EMAIL))) $error = 'Enter the admin name and a valid email.';
    if (!$error && strlen($adminPass) < 10) $error = 'Admin password must be at least 10 characters.';
    if (!$error) {
        try {
            $pdo = new PDO("mysql:host={$db['host']};port={$db['port']};dbname={$db['name']};charset=utf8mb4", $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            $sql = preg_replace('/^--.*$/m', '', (string)file_get_contents(APP_ROOT . '/sql/schema.sql'));
            foreach (preg_split('/;\s*(\n|$)/', $sql) as $stmt) if (trim($stmt) !== '') $pdo->exec($stmt);
            if ($pdo->query('SELECT COUNT(*) FROM users')->fetchColumn() > 0 && empty($_POST['overwrite'])) {
                throw new RuntimeException('This database already has an MMBPL installation. Tick "Use existing data" to keep it, or use an empty database.');
            }
            $st = $pdo->prepare('INSERT INTO users (name, email, password_hash, role) VALUES (?,?,?,"super_admin") ON DUPLICATE KEY UPDATE name=VALUES(name), password_hash=VALUES(password_hash), role="super_admin", active=1');
            $st->execute([$adminName, $adminEmail, password_hash($adminPass, PASSWORD_DEFAULT)]);
            $defaults = [
                'site_name' => trim($_POST['site_name'] ?? '') ?: 'Mian Muhammad Bakhsh Public Library',
                'site_name_ur' => 'میاں محمد بخش پبلک لائبریری', 'site_name_short' => 'Mian Muhammad Bakhsh Public Library', 'site_name_short_ur' => 'میاں محمد بخش پبلک لائبریری',
                'short_name' => 'MMB Public Library', 'site_place' => 'Mirpur, Azad Jammu & Kashmir', 'site_place_ur' => 'میرپور، آزاد جموں و کشمیر',
                'address' => 'Mirpur, Azad Jammu & Kashmir', 'address_ur' => 'میرپور، آزاد جموں و کشمیر', 'map_query' => 'Mian Muhammad Bakhsh Public Library Mirpur',
                'hours_text' => 'Monday to Saturday, 9:00 AM to 5:00 PM', 'hours_text_ur' => 'پیر تا ہفتہ، صبح 9 بجے سے شام 5 بجے تک', 'open_days' => '1,2,3,4,5,6', 'open_from' => '09:00', 'open_to' => '17:00',
                'footer_about_ur' => 'میرپور اور آزاد جموں و کشمیر کے لوگوں کے لیے عوامی لائبریری: کتابیں، مطالعہ گاہیں، مقامی تاریخ اور ہر عمر کے لیے تعلیمی پروگرام۔',
                'max_holds' => '3', 'max_loans_text' => '3', 'review_days' => '2-3', 'covers_openlibrary' => '1', 'show_demo_otp' => !empty($_POST['demo']) ? '1' : '0',
            ];
            $st = $pdo->prepare('INSERT INTO settings (k, v) VALUES (?, ?) ON DUPLICATE KEY UPDATE v = IF(v IS NULL OR v = "", VALUES(v), v)');
            foreach ($defaults as $k => $v) $st->execute([$k, $v]);
            require __DIR__ . '/content.php';
            install_pages($pdo);
            if (!empty($_POST['demo'])) { require __DIR__ . '/demo.php'; install_demo($pdo); }
            $cfg = "<?php\n// Generated by the MMBPL installer on " . date('Y-m-d H:i') . "\nreturn " . var_export([
                'db' => $db, 'timezone' => 'Asia/Karachi', 'debug' => false, 'app_key' => bin2hex(random_bytes(16)),
            ], true) . ";\n";
            if (file_put_contents($configFile, $cfg) === false) throw new RuntimeException('Could not write app/config.php. Check folder permissions.');
            @chmod($configFile, 0640);
            @mkdir(APP_ROOT . '/app/storage', 0755, true);
            $done = true;
        } catch (Throwable $e) {
            $error = $e instanceof PDOException ? 'Database error: ' . $e->getMessage() : $e->getMessage();
        }
    }
}
